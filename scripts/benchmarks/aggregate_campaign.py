#!/usr/bin/env python3
"""Multi-seed campaign aggregator producing Markdown summaries, booktabs LaTeX tables, and Pareto plots.

Scans benchmark CSV outputs (``porespy_study_results.csv``, ``public_rock_results.csv``,
``zn13x_synchrotron_results.csv``) across one or more result directories, aggregates multi-seed
``mean +/- std`` statistics, and exports publication-ready artifacts.
"""

from __future__ import annotations

import argparse
import csv
import json
from collections import defaultdict
from pathlib import Path

import matplotlib
import numpy as np

matplotlib.use("Agg")
import matplotlib.pyplot as plt

CORE_METRICS: list[tuple[str, str, str]] = [
    ("psnr", "PSNR (dB)", "higher"),
    ("ssim_3d_triplanar", "3D SSIM", "higher"),
    ("pore_dice", "Pore Dice", "higher"),
    ("porosity_abs_error", "|dPhi|", "lower"),
    ("through_plane_anisotropy_error", "Stack Aniso.", "lower"),
    ("d_eff_mae", "D_eff MAE", "lower"),
    ("drainage_snwp_rmse", "Drainage RMSE", "lower"),
]


def _discover_csvs(input_dirs: list[Path]) -> list[Path]:
    found: list[Path] = []
    for root in input_dirs:
        if root.is_file() and root.suffix == ".csv":
            found.append(root)
        elif root.is_dir():
            found.extend(sorted(root.rglob("*_results.csv")))
    return found


def _parse_float(val: object) -> float | None:
    if val is None:
        return None
    s = str(val).strip()
    if s in ("", "None", "nan", "NaN", "inf", "-inf", "Infinity", "-Infinity"):
        return None
    try:
        out = float(s)
        return out if np.isfinite(out) else None
    except ValueError:
        return None


def aggregate_csv_files(csv_paths: list[Path], output_dir: Path) -> dict[str, object]:
    output_dir.mkdir(parents=True, exist_ok=True)
    if not csv_paths:
        raise FileNotFoundError("No *_results.csv files found in provided input paths.")

    # Group by (dataset_or_regime, method) -> metric -> list[float]
    grouped: dict[tuple[str, str], dict[str, list[float]]] = defaultdict(lambda: defaultdict(list))
    for p in csv_paths:
        with p.open("r", encoding="utf-8") as f:
            reader = csv.DictReader(f)
            for row in reader:
                ds_key = str(row.get("dataset") or row.get("regime") or p.stem)
                method = str(row.get("method", "unknown"))
                for k, v in row.items():
                    if k in ("dataset", "regime", "pair", "method", "seed"):
                        continue
                    fv = _parse_float(v)
                    if fv is not None:
                        grouped[(ds_key, method)][k].append(fv)

    summary_records: list[dict[str, object]] = []
    for (ds_key, method), metric_map in sorted(grouped.items()):
        rec: dict[str, object] = {
            "dataset": ds_key,
            "method": method,
            "n_seeds": max((len(vals) for vals in metric_map.values()), default=0),
        }
        for m_key, vals in sorted(metric_map.items()):
            arr = np.asarray(vals, dtype=np.float64)
            rec[f"{m_key}_mean"] = float(np.mean(arr))
            rec[f"{m_key}_std"] = float(np.std(arr, ddof=0))
        summary_records.append(rec)

    # 1) JSON summary
    json_out = output_dir / "campaign_summary.json"
    json_out.write_text(json.dumps(summary_records, indent=2) + "\n", encoding="utf-8")

    # 2) Markdown table
    active_metrics = [
        (m, label, direction)
        for m, label, direction in CORE_METRICS
        if any(f"{m}_mean" in r for r in summary_records)
    ]
    md_lines = [
        "# OpenLSR-X Multi-Seed Benchmark Campaign Summary",
        "",
        "| Dataset / Regime | Method | Seeds | "
        + " | ".join(label for _, label, _ in active_metrics)
        + " |",
        "|---|---|---:|" + "|".join("---:" for _ in active_metrics) + "|",
    ]
    for rec in summary_records:
        n_seeds = rec["n_seeds"]
        assert isinstance(n_seeds, int)
        cells: list[str] = []
        for m, _, _ in active_metrics:
            mean_v = rec.get(f"{m}_mean")
            std_v = rec.get(f"{m}_std")
            if isinstance(mean_v, float) and isinstance(std_v, float):
                if n_seeds > 1:
                    cells.append(f"{mean_v:.4f} ± {std_v:.4f}")
                else:
                    cells.append(f"{mean_v:.4f}")
            else:
                cells.append("—")
        md_lines.append(
            f"| `{rec['dataset']}` | `{rec['method']}` | {n_seeds} | " + " | ".join(cells) + " |"
        )
    md_out = output_dir / "campaign_summary.md"
    md_out.write_text("\n".join(md_lines) + "\n", encoding="utf-8")

    # 3) Booktabs LaTeX table for manuscript inclusion
    col_spec = "ll" + ("r" * len(active_metrics))
    tex_lines = [
        "% Auto-generated by scripts/benchmarks/aggregate_campaign.py",
        "\\begin{table}[htbp]",
        "\\centering",
        "\\small",
        f"\\begin{{tabular}}{{{col_spec}}}",
        "\\toprule",
        "Dataset & Method & " + " & ".join(label for _, label, _ in active_metrics) + " \\\\",
        "\\midrule",
    ]
    for rec in summary_records:
        n_seeds = rec["n_seeds"]
        assert isinstance(n_seeds, int)
        ds_tex = str(rec["dataset"]).replace("_", "\\_")
        meth_tex = str(rec["method"]).replace("_", "\\_")
        tex_cells: list[str] = []
        for m, _, _ in active_metrics:
            mean_v = rec.get(f"{m}_mean")
            std_v = rec.get(f"{m}_std")
            if isinstance(mean_v, float) and isinstance(std_v, float):
                if n_seeds > 1:
                    tex_cells.append(f"${mean_v:.4f} \\pm {std_v:.4f}$")
                else:
                    tex_cells.append(f"${mean_v:.4f}$")
            else:
                tex_cells.append("--")
        tex_lines.append(f"{ds_tex} & {meth_tex} & " + " & ".join(tex_cells) + " \\\\")
    tex_lines.extend(
        [
            "\\bottomrule",
            "\\end{tabular}",
            "\\caption{Multi-seed quantitative image, morphological, and transport XCT benchmark summary.}",
            "\\label{tab:openlsrx_campaign}",
            "\\end{table}",
        ]
    )
    tex_out = output_dir / "campaign_table.tex"
    tex_out.write_text("\n".join(tex_lines) + "\n", encoding="utf-8")

    # 4) Trade-off / Pareto figure (PSNR vs Petrophysical/Transport Error)
    fig, axes = plt.subplots(1, 2, figsize=(11, 4.4), dpi=160)
    ax0, ax1 = axes
    for rec in summary_records:
        psnr_m = rec.get("psnr_mean")
        aniso_m = rec.get("through_plane_anisotropy_error_mean")
        deff_m = rec.get("d_eff_mae_mean")
        label = f"{rec['dataset']}:{rec['method']}"
        if isinstance(psnr_m, float) and isinstance(aniso_m, float):
            ax0.scatter(psnr_m, aniso_m, s=55, alpha=0.85)
            ax0.annotate(str(rec["method"]), (psnr_m, aniso_m), fontsize=6.5, alpha=0.85)
        if isinstance(psnr_m, float) and isinstance(deff_m, float):
            ax1.scatter(psnr_m, deff_m, s=55, alpha=0.85, color="#1f77b4")
            ax1.annotate(label.split(":")[-1], (psnr_m, deff_m), fontsize=6.5, alpha=0.85)

    ax0.set_xlabel("3D PSNR (dB, higher is better)")
    ax0.set_ylabel("Through-Plane Stacking Anisotropy (lower is better)")
    ax0.set_title("Voxel PSNR vs. 3D Isotropy")
    ax0.grid(True, alpha=0.25)

    ax1.set_xlabel("3D PSNR (dB, higher is better)")
    ax1.set_ylabel("Effective Diffusivity MAE |D_eff - D_eff^HR| (lower is better)")
    ax1.set_title("Voxel PSNR vs. Pore-Scale Transport Fidelity")
    ax1.grid(True, alpha=0.25)

    fig.tight_layout()
    fig_out = output_dir / "campaign_tradeoffs.png"
    fig.savefig(fig_out)
    plt.close(fig)

    return {
        "n_groups": len(summary_records),
        "json_path": str(json_out),
        "markdown_path": str(md_out),
        "latex_path": str(tex_out),
        "figure_path": str(fig_out),
    }


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Aggregate multi-seed OpenLSR-X benchmark CSVs into Markdown, LaTeX, and plots."
    )
    parser.add_argument(
        "--inputs",
        nargs="+",
        default=["results"],
        help="Directories or CSV files to aggregate (default: results).",
    )
    parser.add_argument(
        "--output-dir",
        default="results/campaign_summary",
        help="Output directory for aggregated tables and figures.",
    )
    ns = parser.parse_args()
    csvs = _discover_csvs([Path(p) for p in ns.inputs])
    info = aggregate_csv_files(csvs, Path(ns.output_dir))
    print(
        f"[aggregate_campaign] Aggregated {info['n_groups']} method groups -> "
        f"{info['markdown_path']} & {info['latex_path']}"
    )


if __name__ == "__main__":
    main()
